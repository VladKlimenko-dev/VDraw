namespace VDraw.Ui.Avalon;

/// <summary>
/// Идёт ли сейчас набор в поле ввода Avalonia.
///
/// Нужно главному окну: оно перехватывает клавиши в ProcessCmdKey, до того
/// как их получит контрол с фокусом, и обязано отличать набор текста от
/// команды. С полями WinForms это решалось проверкой типа контрола
/// с фокусом, а поля Avalonia так не видны: с точки зрения WinForms фокус
/// стоит на хосте — одном контроле на всю панель, — и что внутри него,
/// переименовывают фигуру или нажали кнопку, по типу не отличить.
///
/// Поэтому поля отмечаются сами, на входе и выходе фокуса. Статически,
/// а не свойством панели: хостов Avalonia в приложении несколько —
/// панель свойств и полосы инструментов, — и спрашивать каждый
/// пришлось бы по списку, который легко забыть пополнить.
///
/// Запоминается ссылка на поле, а не счётчик: при переходе из поля в поле
/// Avalonia поднимает LostFocus прежнего и GotFocus нового, и при любом
/// их порядке сравнение по ссылке не оставит признак ни взведённым
/// без нужды, ни сброшенным раньше времени.
/// </summary>
internal static class AvTextInput
{
	private static object? _focused;

	public static bool IsFocused => _focused != null;

	public static void Entered(object field) => _focused = field;

	public static void Left(object field)
	{
		if (ReferenceEquals(_focused, field))
			_focused = null;
	}
}
